% =========================================================================
% 时频图数据集增量拼接工具 (MATLAB)
% =========================================================================
clear; clc;

% 1. 定义文件路径 (请修改为你自己的路径)
file_old = 'E:\tm_Dronfa_xy\Dataset_Merged_All_v2.mat';  % 原来的4类数据
file_new = 'E:\tm_Dronfa_xy\TM_Images_64x64_50ms_v7_backgruand.mat'; % 新生成的几类数据
file_merged = 'E:\tm_Dronfa_xy\Dataset_Merged_All_v2.mat'; % 拼接后的保存路径

fprintf('正在加载旧数据集...\n');
old_data = load(file_old);

fprintf('正在加载新数据集...\n');
new_data = load(file_new);

% =========================================================================
% ★ 2. 确认你的变量名 (请根据你的 .mat 里的实际变量名修改)
% 假设你的时频图矩阵叫 'X_spectrograms'，标签叫 'Y_labels'
% =========================================================================
var_name_X = 'all_Images'; % 替换为你的特征变量名
var_name_Y = 'all_Labels';       % 替换为你的标签变量名

% 提取变量
X_old = old_data.(var_name_X);
Y_old = old_data.(var_name_Y);

X_new = new_data.(var_name_X);
Y_new = new_data.(var_name_Y);

% =========================================================================
% 3. 维度检查与拼接
% 假设你的维度是 [样本数, 64, 64] 或者 [样本数, 特征维度]
% =========================================================================
fprintf('检查维度兼容性...\n');
disp(['旧特征维度: ', num2str(size(X_old))]);
disp(['新特征维度: ', num2str(size(X_new))]);

% 沿着第 1 维（样本维度）进行垂直拼接
% 注意：如果你的样本维度在最后面（比如 64x64x样本数），请用 cat(3, X_old, X_new)
try
    all_Images = cat(1, X_old, X_new); % 拼接特征
    all_Labels = cat(1, Y_old, Y_new); % 拼接标签
    fprintf('拼接成功！合并后总样本数: %d\n', size(all_Images, 1));
catch ME
    error('拼接失败！请检查旧数据和新数据除了样本数以外的维度是否完全一致。错误信息: %s', ME.message);
end

% =========================================================================
% 4. 保存为新的大文件 (极其关键的一步)
% =========================================================================
fprintf('正在保存合并后的数据集到: %s\n', file_merged);

% ★ 避坑指南：如果拼接后的文件大于 2GB，必须加上 '-v7.3' 参数，否则会报错！
save(file_merged, 'all_Images', 'all_Labels', '-v7.3');

fprintf('数据集增量拼接完成！\n');